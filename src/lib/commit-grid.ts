export interface CommitGridConfig {
    enabled: boolean;
    text: string;
    repoTag?: string;
    subBadge?: string;
    footerNote?: string;
}

export function buildCommitGridMatrix(text: string, totalCols: number = 24): number[][] {
    const cleanText = (text || '256').trim().toUpperCase();

    // Exact match for 256 to mirror the canonical Programmer's Day spacing
    if (cleanText === '256') {
        const grid: number[][] = Array.from({ length: 7 }, () => Array(totalCols).fill(0));
        const d2 = BITMAP_FONT_7X4['2'];
        const d5 = BITMAP_FONT_7X4['5'];
        const d6 = BITMAP_FONT_7X4['6'];

        for (let r = 0; r < 7; r++) {
            for (let c = 0; c < 4; c++) {
                if (d2[r][c]) grid[r][3 + c] = 4;
                if (d5[r][c]) grid[r][10 + c] = 4;
                if (d6[r][c]) grid[r][17 + c] = 4;
            }
        }

        const faintCoords: [number, number][] = [
            [0, 0], [1, 1], [3, 0], [5, 1], [6, 0],
            [0, 8], [2, 7], [4, 9], [6, 8],
            [1, 14], [3, 15], [5, 16],
            [0, 22], [2, 21], [3, 23], [5, 22], [6, 23]
        ];
        for (const [r, c] of faintCoords) {
            if (c < totalCols && grid[r][c] === 0) grid[r][c] = (r + c) % 2 === 0 ? 2 : 1;
        }
        return grid;
    }

    const grid: number[][] = Array.from({ length: 7 }, () => Array(totalCols).fill(0));

    // Measure total glyph width with 1-col gap between glyphs
    const glyphs = cleanText.split('').map(char => BITMAP_FONT_7X4[char] || BITMAP_FONT_7X4[' ']);
    const totalGlyphWidth = glyphs.reduce((sum, g) => sum + g[0].length, 0) + Math.max(0, glyphs.length - 1);

    // Center glyphs inside totalCols
    let startCol = Math.max(1, Math.floor((totalCols - totalGlyphWidth) / 2));

    for (const glyph of glyphs) {
        const charWidth = glyph[0].length;
        for (let r = 0; r < 7; r++) {
            for (let c = 0; c < charWidth; c++) {
                if (startCol + c < totalCols && glyph[r][c]) {
                    grid[r][startCol + c] = 4;
                }
            }
        }
        startCol += charWidth + 1;
    }

    // Add subtle background commit scatter in outer unused columns
    for (let c = 0; c < totalCols; c++) {
        const hasGlyph = grid.some(row => row[c] === 4);
        if (!hasGlyph && (c < 3 || c >= totalCols - 3 || c % 5 === 0)) {
            const r = (c * 3 + 2) % 7;
            if (grid[r][c] === 0) {
                grid[r][c] = c % 2 === 0 ? 2 : 1;
            }
        }
    }

    return grid;
}
